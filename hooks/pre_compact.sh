#!/usr/bin/env bash
# PreCompact hook (универсальный).
# Перед сжатием контекста напоминает обновить docs/SESSION_STATE.md,
# чтобы следующая сессия не потеряла состояние.
# Молча ничего не делает, если такого файла в проекте нет.

set -u

CUR_DIR="${CLAUDE_PROJECT_DIR:-$PWD}"
SESSION_STATE="$CUR_DIR/docs/SESSION_STATE.md"

[ -f "$SESSION_STATE" ] || exit 0

cat <<MSG
## Pre-compact reminder

Перед сжатием контекста обнови файл \`docs/SESSION_STATE.md\`.

Конкретно — освежи секции:
- **Где мы сейчас** — что делали последние ходы, на чём остановились.
- **Следующий шаг** — с чего начнёт следующая сессия.
- **Принятые решения** — новые договорённости этой сессии.

Правила:
- Сохрани существующее содержимое (только добавляй/уточняй, не сноси).
- Не более ~50 строк суммарно — это чекпойнт, не лог.
- Если ничего значимого не изменилось — обнови только дату вверху файла.

Сделай это сейчас, до того как контекст будет сжат.
MSG
